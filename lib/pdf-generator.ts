import { jsPDF } from 'jspdf';
import { BusinessIdea, UserProfile, Scheme } from './types';

export function generateBusinessPlanPDF(
  idea: BusinessIdea,
  profile: UserProfile,
  schemes: Scheme[]
) {
  const doc = new jsPDF();

  // Header background banner (Sage 600 - #5E7A50)
  doc.setFillColor(94, 122, 80);
  doc.rect(0, 0, 210, 38, 'F');

  // Title
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(22);
  doc.setFont('helvetica', 'bold');
  doc.text('GRAM UDYAM AI', 14, 18);

  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  doc.text(`Official Rural Micro-Enterprise Plan | ${profile.name || 'Beneficiary'} - ${profile.village || 'Village'}, ${profile.district || 'District'}`, 14, 28);

  // Section 1: Business Overview
  doc.setTextColor(38, 51, 34); // Sage 900
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text(`1. Selected Business: ${idea.name}`, 14, 52);

  doc.setLineWidth(0.5);
  doc.setDrawColor(211, 223, 203); // Sage 200
  doc.line(14, 56, 196, 56);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(30, 42, 32);

  const overviewText = [
    `Category: ${idea.category}`,
    `Initial Setup Cost: ${idea.setupCostFormatted} (Rs. ${idea.setupCost.toLocaleString('en-IN')})`,
    `Projected Net Monthly Profit: Rs. ${idea.monthlyProfit.toLocaleString('en-IN')}`,
    `Estimated Payback Period: ${idea.paybackMonths} Months`,
    `Space Requirement: ${idea.spaceRequired}`,
    `Target Buyers: Within ${idea.buyersWithinKm} km radius (${idea.confidenceMandis} local mandis tracked)`
  ];

  let y = 65;
  overviewText.forEach(line => {
    doc.text(`•  ${line}`, 18, y);
    y += 7;
  });

  // Section 2: Beneficiary Profile
  y += 5;
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(38, 51, 34);
  doc.text('2. Entrepreneur Profile Summary', 14, y);
  y += 4;
  doc.line(14, y, 196, y);
  y += 8;

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(30, 42, 32);
  doc.text(`Beneficiary Name: ${profile.name || 'Lakshmi'}`, 18, y); y += 6;
  doc.text(`Location: ${profile.village || 'Melur'}, ${profile.block || 'Block B13'}, ${profile.district || 'Madurai'}`, 18, y); y += 6;
  doc.text(`Personal Investment Capacity: Rs. ${profile.savings.toLocaleString('en-IN')}`, 18, y); y += 6;
  doc.text(`Land Holding: ${profile.land} | Time Availability: ${profile.time}`, 18, y); y += 6;
  doc.text(`Skills Registered: ${profile.skills.join(', ') || 'Farming, Cooking'}`, 18, y); y += 6;
  doc.text(`SHG Member: ${profile.shgMember ? 'Yes (NRLM Registered)' : 'No'}`, 18, y); y += 10;

  // Section 3: Recommended Government Schemes
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(38, 51, 34);
  doc.text('3. Matched Government Financial Schemes', 14, y);
  y += 4;
  doc.line(14, y, 196, y);
  y += 8;

  schemes.slice(0, 3).forEach(sc => {
    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(94, 122, 80);
    doc.text(`[${sc.code}] ${sc.name}`, 18, y);
    y += 6;
    doc.setFontSize(9);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(86, 101, 88);
    doc.text(`Status: ${sc.statusText} | Required Documents: ${sc.documentsReady} of ${sc.documentsTotal} ready`, 22, y);
    y += 5;
    doc.text(`Description: ${sc.description}`, 22, y);
    y += 8;
  });

  // Section 4: 6-Step Action Plan
  y += 4;
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(38, 51, 34);
  doc.text('4. Step-by-Step Implementation Timeline', 14, y);
  y += 4;
  doc.line(14, y, 196, y);
  y += 8;

  const steps = [
    'Step 1: Finalize business choice and local market survey (Completed)',
    'Step 2: Submit loan / subsidy application under PMEGP or MUDRA (Completed)',
    'Step 3: Gather documents (Aadhaar, Passbook, Project Estimate) - 4/6 ready',
    'Step 4: Visit nearest CSC / Bank Branch to process subsidy disbursement',
    'Step 5: Procure raw materials, machinery & setup processing unit',
    'Step 6: Commence production & log weekly sales in Gram Udyam app'
  ];

  doc.setFontSize(9.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(30, 42, 32);
  steps.forEach(st => {
    doc.text(st, 18, y);
    y += 6;
  });

  // Footer / Disclaimer
  y = 280;
  doc.setFontSize(8);
  doc.setTextColor(150, 150, 150);
  doc.text('Generated by Gram Udyam AI Engine. Aligned with UN SDG 8 (Decent Work & Economic Growth). All financial estimates are indicative.', 14, y);

  doc.save(`${idea.id}-business-plan.pdf`);
}
